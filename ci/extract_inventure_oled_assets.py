"""Reproduce the dashboard sprites and the MCU fault glyphs from Inventure 1.6.1 r0323."""
import argparse
import base64
from hashlib import sha256
import json
from pathlib import Path
import struct
import zlib


BASE = 0x08010000
APPLICATION_SHA256 = '9b980ba04531fac4425b77a23969076d24d8f25629fc2a501ac05d262c142268'
# Addresses in the Inventure resource inventory. Use the same names on both processors.
DESCRIPTORS = {
    'error': 0x0802A3CC, 'warning': 0x0802F9CC, 'filecheck': 0x0802A684,
    'information': 0x0802AAB4, 'settings': 0x0802F1F8, 'progress': 0x0802E158,
    'wait': 0x0802F738, 'sleep': 0x0802F3CC, 'maintenance': 0x0802CE70,
    'material': 0x0802D058,
}


def unpack_frame(data, size):
    source = iter(data)
    marker = next(source)
    out = bytearray()

    def number(first):
        value = first & 127
        while first & 128:
            first = next(source)
            value = (value << 7) | (first & 127)
        return value

    for byte in source:
        if byte != marker:
            out.append(byte)
        else:
            byte = next(source)
            if byte:
                length = number(byte)
                distance = number(next(source))
                if not 0 < distance <= len(out) or length > size - len(out):
                    raise ValueError('Invalid Inventure OLED frame back-reference')
                for _ in range(length):
                    out.append(out[-distance])
            else:
                out.append(marker)
        if len(out) > size:
            raise ValueError('Oversize Inventure OLED frame')
    if len(out) != size:
        raise ValueError('Incomplete Inventure OLED frame')
    return bytes(out)


def extract(app, destination, header):
    if sha256(app).hexdigest() != APPLICATION_SHA256:
        raise ValueError('Expected the audited Inventure 1.6.1 r0323 application')
    symbols = {}
    diagnostic = ['/* Inventure r0323 monochrome error/warning glyphs, generated by ci/extract_inventure_oled_assets.py. */']
    for name, address in DESCRIPTORS.items():
        width, height, count, flags, delay, table, transform = struct.unpack_from('<4B3I', app, address - BASE)
        if (width, height, flags, transform) != (50, 50, 0, 0):
            raise ValueError('Unexpected descriptor for ' + name)
        frames = []
        for pointer, in struct.iter_unpack('<I', app[table-BASE:table-BASE+4*count]):
            offset = pointer - BASE
            length, = struct.unpack_from('<I', app, offset)
            pixels = unpack_frame(app[offset+4:offset+4+length], width * height // 2)
            frames.append(dict(sha256=sha256(pixels).hexdigest(),
                               zlib_b64=base64.b64encode(zlib.compress(pixels, 9)).decode()))
            if name in ('warning', 'error'):
                # SSD1322 RAM stays at one scanline on the MCU. One bit per pixel in flash.
                diagnostic.append('static const uint8_t local_' + name + '_rows[50][7] = {')
                for row in range(height):
                    bits = 0
                    for x in range(width):
                        b = pixels[row*25 + x//2]
                        bits |= int((b & 15 if x % 2 else b >> 4) >= 8) << (55-x)
                    diagnostic.append('    {' + ','.join('0x%02x' % n for n in bits.to_bytes(7, 'big')) + '},')
                diagnostic.append('};')
        symbols[name] = dict(descriptor='0x%08X' % address, width=width, height=height, frame_ms=delay, frames=frames)
    catalog = dict(source='Zortrax Inventure 1.6.1 r0323', application_sha256=APPLICATION_SHA256, symbols=symbols)
    destination.write_text(json.dumps(catalog, indent=2) + '\n')
    header.write_text('\n'.join(diagnostic) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('application', 'catalog', 'mcu_header'):
        parser.add_argument(name, type=Path)
    args = parser.parse_args()
    extract(args.application.read_bytes(), args.catalog, args.mcu_header)
